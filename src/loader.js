/* Effix auto-loader — for plain pages without a bundler.
   <script src="…/dist/effix.auto.min.js" defer></script>
   Scans the page for efx-* classes and loads ONLY the matching feature files
   (dist/features/<name>.min.js + .css; chart types also load the shared chart toolkit once).
   Add <div class="efx-confetti"> and confetti.min.js is fetched; nothing else is.
   With <html data-efx-observe> it keeps watching, so elements added later load their files too.
   Options: <script … data-efx-base="https://cdn/…/dist/"> to load files from elsewhere. */

/** manifest: { effects: { name: [selector, hasCss, needsChartKit] } } (generated by build.js) */
export function autoload(api, manifest) {
  const doc = document;
  const me = doc.currentScript;
  const base = (me && me.dataset.efxBase) || (me && me.src ? me.src.replace(/[^/]*$/, '') : 'dist/');
  const requested = new Map(); // name -> Promise
  const pending = new Set();

  const addCss = href => {
    if (doc.querySelector(`link[href="${href}"]`)) return;
    const l = doc.createElement('link');
    l.rel = 'stylesheet';
    l.href = href;
    doc.head.appendChild(l);
  };
  const addJs = (src, key) => new Promise(resolve => {
    const s = doc.createElement('script');
    s.src = src;
    s.async = true;
    s.onload = s.onerror = () => { pending.delete(key); resolve(); };
    pending.add(key);
    doc.head.appendChild(s);
  });

  /** Load one feature by name. Chart-type features first load the shared chart toolkit (once).
      Resolves when its script has run. */
  function load(name) {
    if (requested.has(name)) return requested.get(name);
    const m = manifest.effects[name];
    let p;
    if (name === '_chartkit') {
      addCss(`${base}features/_chartkit.min.css`);
      p = addJs(`${base}features/_chartkit.min.js`, name);
    } else if (!m) p = Promise.resolve();
    else {
      if (m[1]) addCss(`${base}features/${name}.min.css`);
      p = (m[2] ? load('_chartkit') : Promise.resolve()).then(() => addJs(`${base}features/${name}.min.js`, name));
    }
    requested.set(name, p);
    return p;
  }

  const has = (root, sel) => (root.nodeType === 1 && root.matches(sel)) || !!root.querySelector(sel);

  /** Find efx-* features used inside root and load their files. */
  function scan(root = doc) {
    const known = api.features();
    for (const name in manifest.effects) {
      if (!requested.has(name) && !known.includes(name) && has(root, manifest.effects[name][0])) load(name);
    }
  }

  api.load = load;
  api.autoload = scan;
  addCss(base + 'effix.core.min.css');

  const start = () => {
    scan();
    if (doc.documentElement.hasAttribute('data-efx-observe') && typeof MutationObserver !== 'undefined') {
      new MutationObserver(rs => rs.forEach(r => r.addedNodes.forEach(n => { if (n.nodeType === 1) scan(n); })))
        .observe(doc.body, { childList: true, subtree: true });
    }
  };
  if (doc.readyState === 'loading') doc.addEventListener('DOMContentLoaded', start, { once: true });
  else start();
}
