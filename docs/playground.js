/* Effix playground: pick a base element, stack effects/charts on it, tweak options, copy the HTML.
   Data comes from playground-data.js (generated by docs.js). No dependencies, ES2019. */
(function () {
  'use strict';
  var DATA = (window.EFX_PLAYGROUND && window.EFX_PLAYGROUND.features) || [];
  var html = document.documentElement;
  var $ = function (id) { return document.getElementById(id); };
  var CDN = 'https://cdn.jsdelivr.net/gh/asticore';

  /* ---------- small helpers ---------- */
  var store = {
    get: function (k) { try { return localStorage.getItem(k); } catch (e) { return null; } },
    set: function (k, v) { try { localStorage.setItem(k, v); } catch (e) {} }
  };
  function h(tag, props, kids) {
    var el = document.createElement(tag);
    Object.keys(props || {}).forEach(function (k) {
      var v = props[k];
      if (v === false || v == null) return;
      if (k === 'text') el.textContent = v;
      else if (k === 'class') el.className = v;
      else el.setAttribute(k, v === true ? '' : v);
    });
    (kids || []).forEach(function (c) { if (c) el.appendChild(typeof c === 'string' ? document.createTextNode(c) : c); });
    return el;
  }
  function byName(n) { for (var i = 0; i < DATA.length; i++) if (DATA[i].name === n) return DATA[i]; return null; }
  function escAttr(v) { return String(v).replace(/&/g, '&amp;').replace(/"/g, '&quot;'); }
  function toB64(s) {
    var bytes = new TextEncoder().encode(s), bin = '';
    for (var i = 0; i < bytes.length; i++) bin += String.fromCharCode(bytes[i]);
    return btoa(bin).replace(/\+/g, '-').replace(/\//g, '_').replace(/=+$/, '');
  }
  function fromB64(s) {
    s = s.replace(/-/g, '+').replace(/_/g, '/');
    while (s.length % 4) s += '=';
    var bin = atob(s), bytes = new Uint8Array(bin.length);
    for (var i = 0; i < bin.length; i++) bytes[i] = bin.charCodeAt(i);
    return new TextDecoder().decode(bytes);
  }

  /* ---------- base elements ---------- */
  var BASES = {
    button: { label: 'Button', tag: 'button', cls: 'btn', attrs: { type: 'button' }, inner: 'Button' },
    card: { label: 'Card', tag: 'div', cls: 'card', inner: '\n  <div class="card-body stack gap-2">\n    <h3 class="card-title m-0">Card title</h3>\n    <p class="m-0">A short sentence of supporting text.</p>\n  </div>\n' },
    hero: { label: 'Hero section', tag: 'section', cls: 'card p-8 stack gap-3 justify-center', attrs: { style: 'min-height:320px' },
      inner: '\n  <h2 class="text-4xl font-bold m-0">Build something remarkable</h2>\n  <p class="m-0 max-w-xl">Effects that need JavaScript, applied with plain classes.</p>\n  <div><button class="btn" type="button">Get started</button></div>\n' },
    heading: { label: 'Heading text', tag: 'h2', cls: 'text-4xl font-bold m-0', inner: 'Effects with plain classes' },
    image: { label: 'Image', tag: 'div', cls: 'rounded-lg', attrs: { role: 'img', 'aria-label': 'Sample image', style: 'width:320px;max-width:100%;height:200px;background:linear-gradient(135deg,#6366f1,#ec4899)' }, inner: '' },
    stat: { label: 'Stat card', tag: 'div', cls: 'card', inner: '\n  <div class="card-body stack gap-1">\n    <p class="label m-0">Revenue</p>\n    <p class="text-4xl font-bold m-0">1,284</p>\n    <p class="text-sm text-muted m-0">+12% this week</p>\n  </div>\n' },
    chart: { label: 'Chart box', tag: 'div', cls: '', attrs: { style: 'width:100%;height:260px' }, inner: '' },
    own: { label: "Feature's own example", own: true }
  };
  var BASE_ORDER = ['button', 'card', 'hero', 'heading', 'image', 'stat', 'chart', 'own'];

  /* ---------- state ---------- */
  var state = { base: 'button', sel: [], theme: '', reduce: false, width: 'full', collapsed: {} };
  var errorsByField = {};   // field id -> message (JSON problems)

  function selOf(name) { for (var i = 0; i < state.sel.length; i++) if (state.sel[i].name === name) return state.sel[i]; return null; }

  function parseExample(feat) {
    var d = document.createElement('div');
    d.innerHTML = feat.example || '';
    return d;
  }
  /* Charts need data: seed their options from the feature's first example. */
  function seedFromExample(feat, item) {
    var d = parseExample(feat), el = null;
    try { el = d.querySelector('.' + item.cls); } catch (e) {}
    if (!el) return;
    Array.prototype.forEach.call(el.attributes, function (a) {
      if (!/^data-efx-/.test(a.name)) return;
      var opt = feat.options.filter(function (o) { return o.attr === a.name; })[0];
      if (a.value === '' && !(opt && opt.type === 'bool')) return;
      item.opts[a.name] = a.value === '' ? 'true' : compactJSON(a.value);
    });
    var script = el.querySelector('script[type="application/json"]');
    if (script && !item.opts['data-efx-data']) item.opts['data-efx-data'] = compactJSON(script.textContent);
  }
  function compactJSON(s) {
    var t = String(s).trim();
    if (!/^[\[{]/.test(t)) return s;
    try { return JSON.stringify(JSON.parse(t)); } catch (e) { return s; }
  }
  function addFeature(name, cls, opts) {
    var feat = byName(name);
    if (!feat || selOf(name)) return null;
    var item = { name: name, cls: feat.classes.indexOf(cls) >= 0 ? cls : feat.classes[0], opts: opts || {} };
    if (feat.kind === 'chart') {
      state.sel = state.sel.filter(function (s) { var f = byName(s.name); return !(f && f.kind === 'chart'); });
      if (!opts) seedFromExample(feat, item);
    }
    state.sel.push(item);
    return item;
  }
  function removeFeature(name) { state.sel = state.sel.filter(function (s) { return s.name !== name; }); }

  /* ---------- markup generation ---------- */
  function serializeOpen(el) {
    var attrs = Array.prototype.map.call(el.attributes, function (a) {
      var v = a.value;
      if (v.indexOf('"') >= 0 && v.indexOf("'") < 0) return a.name + "='" + v.replace(/&/g, '&amp;') + "'";
      return a.name + '="' + escAttr(v) + '"';
    });
    var long = attrs.length > 2 || attrs.join(' ').length > 70;
    return '<' + el.localName + (attrs.length ? ' ' + attrs.join(long ? '\n  ' : ' ') : '') + '>';
  }

  function build() {
    var holder = document.createElement('div'), root, target, errors = [], hints = [];
    errorsByField = {};
    var first = state.sel[0] ? byName(state.sel[0].name) : null;
    if (state.base === 'own') {
      var ownFeat = null;
      for (var i = 0; i < state.sel.length; i++) { var f = byName(state.sel[i].name); if (f && f.example) { ownFeat = f; break; } }
      if (ownFeat) holder.innerHTML = ownFeat.example.trim();
      else { holder.innerHTML = '<div class="card p-6">Select a feature to load its own example.</div>'; hints.push("Pick a feature to use its own example markup."); }
      root = holder.firstElementChild;
      target = root;
      if (ownFeat) {
        var sels = ownFeat.classes.map(function (c) { return '.' + c; }).join(',');
        try { target = holder.querySelector(sels) || root; } catch (e) { target = root; }
      }
    } else {
      var b = BASES[state.base] || BASES.button;
      root = document.createElement(b.tag);
      if (b.cls) root.className = b.cls;
      Object.keys(b.attrs || {}).forEach(function (k) { root.setAttribute(k, b.attrs[k]); });
      root.innerHTML = b.inner;
      holder.appendChild(root);
      target = root;
      if (state.base === 'chart' && !state.sel.some(function (s) { var f = byName(s.name); return f && f.kind === 'chart'; })) hints.push('Pick a chart in the Charts group to fill this box.');
    }
    if (!target) { holder.innerHTML = '<div class="card p-6">Nothing to preview.</div>'; root = target = holder.firstElementChild; }
    void first;

    state.sel.forEach(function (item) {
      var feat = byName(item.name);
      if (!feat) return;
      target.classList.add(item.cls);
      Object.keys(item.opts).forEach(function (attr) {
        var v = item.opts[attr];
        if (v == null || String(v).trim() === '') return;
        var opt = feat.options.filter(function (o) { return o.attr === attr; })[0];
        if (opt && opt.type === 'json' || /^[\[{]/.test(String(v).trim())) {
          var fid = fieldId(item.name, attr), t = String(v).trim();
          if (/^[\[{]/.test(t)) {
            try { v = JSON.stringify(JSON.parse(t)); }
            catch (e) { errorsByField[fid] = e.message; errors.push(attr + ' (' + feat.title + '): invalid JSON. ' + e.message); return; }
          }
        }
        target.setAttribute(attr, v);
      });
    });

    var inner = root.innerHTML.replace(/^\n/, '\n');
    var out;
    if (root === target || state.base !== 'own') {
      var multi = inner.indexOf('\n') >= 0;
      out = serializeOpen(root) + inner + (multi && !/\n$/.test(inner) ? '\n' : '') + '</' + root.localName + '>';
      if (holder.children.length > 1) out += '\n' + Array.prototype.slice.call(holder.children, 1).map(function (e) { return e.outerHTML; }).join('\n');
    } else {
      out = holder.innerHTML.trim();
    }
    return { html: out, errors: errors, hints: hints };
  }

  function headTags() {
    // The auto-loader fetches only the files for the efx-* classes on the page (charts add-on included).
    return [
      '<link rel="stylesheet" href="' + CDN + '/shine@main/dist/shine.min.css">',
      '<script src="' + CDN + '/effix@main/dist/effix.auto.min.js" defer></script>'
    ].join('\n');
  }

  /* ---------- share link ---------- */
  function encodeState() {
    var o = { b: state.base, f: state.sel.map(function (s) { return [s.name, s.cls, s.opts]; }) };
    if (state.theme) o.t = state.theme;
    if (state.reduce) o.r = 1;
    if (state.width !== 'full') o.w = state.width;
    return toB64(JSON.stringify(o));
  }
  function restoreState() {
    var hash = location.hash.replace(/^#/, '');
    if (!hash) return false;
    try {
      var o = JSON.parse(fromB64(hash));
      if (!o || typeof o !== 'object') return false;
      state.base = BASES[o.b] ? o.b : 'button';
      state.sel = [];
      (Array.isArray(o.f) ? o.f : []).forEach(function (r) {
        if (!Array.isArray(r) || typeof r[0] !== 'string') return;
        var opts = {};
        if (r[2] && typeof r[2] === 'object') Object.keys(r[2]).forEach(function (k) { if (/^data-efx-[\w-]+$/.test(k) && typeof r[2][k] === 'string') opts[k] = r[2][k]; });
        addFeature(r[0], r[1], opts);
      });
      state.theme = o.t === 'light' || o.t === 'dark' ? o.t : '';
      state.reduce = !!o.r;
      state.width = o.w === '375' || o.w === '768' ? o.w : 'full';
      return true;
    } catch (e) { return false; }
  }

  /* ---------- rendering the controls ---------- */
  var listEl = $('pg-list'), optsEl = $('pg-opts'), stage = $('pg-stage'), statusEl = $('pg-status');
  function fieldId(name, attr) { return 'pg-o-' + name + '-' + attr.replace(/^data-efx-/, ''); }

  function buildList() {
    listEl.textContent = '';
    var groups = [];
    DATA.forEach(function (f) { if (groups.indexOf(f.group) < 0) groups.push(f.group); });
    groups.forEach(function (g) {
      var wrap = h('div', { 'data-group': g, role: 'group', 'aria-label': g });
      wrap.appendChild(h('div', { class: 'pg-group', text: g }));
      var isCharts = g === 'Charts';
      if (isCharts) {
        var none = h('label', { class: 'pg-row', 'data-row': '', 'data-text': 'no chart none' }, [
          h('input', { type: 'radio', name: 'pg-chart', value: '', class: 'checkbox', id: 'pg-chart-none' }), ' No chart']);
        wrap.appendChild(none);
      }
      DATA.filter(function (f) { return f.group === g; }).forEach(function (f) {
        var id = 'pg-f-' + f.name;
        var input = h('input', { type: isCharts ? 'radio' : 'checkbox', class: 'checkbox', id: id, name: isCharts ? 'pg-chart' : 'pg-feat', value: f.name });
        var row = h('div', { class: 'pg-row', 'data-row': '', 'data-text': (f.title + ' ' + f.name + ' ' + f.group).toLowerCase() }, [
          input, h('label', { for: id, text: f.title })]);
        if (f.classes.length > 1) {
          var sel = h('select', { class: 'select input-sm', id: 'pg-c-' + f.name, 'aria-label': f.title + ' variant', 'data-cls-for': f.name, hidden: true });
          f.classes.forEach(function (c) { sel.appendChild(h('option', { value: c, text: c.replace(/^efx-/, '') })); });
          row.appendChild(sel);
        }
        wrap.appendChild(row);
      });
      listEl.appendChild(wrap);
    });
  }
  function syncList() {
    Array.prototype.forEach.call(listEl.querySelectorAll('input[name=pg-feat],input[name=pg-chart]'), function (inp) {
      if (inp.id === 'pg-chart-none') { inp.checked = !state.sel.some(function (s) { return byName(s.name).kind === 'chart'; }); return; }
      var item = selOf(inp.value);
      inp.checked = !!item;
      var sel = $('pg-c-' + inp.value);
      if (sel) { sel.hidden = !item; if (item) sel.value = item.cls; }
    });
  }
  function filterList() {
    var q = $('pg-search').value.trim().toLowerCase();
    Array.prototype.forEach.call(listEl.querySelectorAll('[data-group]'), function (g) {
      var any = false;
      Array.prototype.forEach.call(g.querySelectorAll('[data-row]'), function (r) {
        var show = !q || r.getAttribute('data-text').indexOf(q) >= 0 || !!r.querySelector('input:checked');
        r.hidden = !show;
        if (show) any = true;
      });
      g.hidden = !any;
    });
  }

  function optionField(item, feat, opt) {
    var id = fieldId(item.name, opt.attr), cur = item.opts[opt.attr] || '', desc = id + '-d';
    var box = h('div', { class: 'pg-opt' }), label = h('label', { for: id }, [h('code', { text: opt.attr })]), input;
    var hint = h('span', { class: 'hint', id: desc, text: (opt.def ? 'Default: ' + opt.def + '. ' : '') + opt.desc });
    if (opt.type === 'bool') {
      var st = cur === 'true' || cur === 'false' ? cur : '';
      input = h('input', { type: 'checkbox', class: 'checkbox', id: id, 'data-state': st, 'aria-describedby': desc });
      var txt = h('span', { class: 'text-sm', 'data-for': id });
      var paint = function () {
        var s = input.getAttribute('data-state');
        input.indeterminate = s === '';
        input.checked = s === 'true';
        txt.textContent = s === '' ? 'default (' + opt.def + ')' : s;
      };
      input.addEventListener('click', function () {
        var s = input.getAttribute('data-state');
        input.setAttribute('data-state', s === '' ? 'true' : s === 'true' ? 'false' : '');
        paint();
        setOpt(item, opt.attr, input.getAttribute('data-state'));
      });
      paint();
      box.appendChild(h('div', { class: 'flex items-center gap-2' }, [input, label, txt]));
    } else if (opt.type === 'json') {
      input = h('textarea', { class: 'textarea pg-textarea', id: id, spellcheck: 'false', rows: '5', placeholder: opt.def || 'JSON or comma list', 'aria-describedby': desc + ' ' + id + '-e' });
      input.value = cur;
      input.addEventListener('input', function () { setOpt(item, opt.attr, input.value); });
      box.appendChild(label); box.appendChild(input);
      box.appendChild(h('span', { class: 'hint', id: id + '-e', 'data-err-for': id }));
    } else {
      input = h('input', { type: opt.type === 'number' ? 'number' : 'text', step: opt.type === 'number' ? 'any' : false, class: 'input input-sm', id: id, placeholder: opt.def, 'aria-describedby': desc });
      input.value = cur;
      input.addEventListener('input', function () { setOpt(item, opt.attr, input.value); });
      box.appendChild(label); box.appendChild(input);
    }
    if (opt.type !== 'bool') box.appendChild(hint); else box.appendChild(hint);
    return box;
  }
  function buildOptions() {
    optsEl.textContent = '';
    state.sel.forEach(function (item) {
      var feat = byName(item.name);
      var known = feat.options.map(function (o) { return o.attr; });
      var extras = Object.keys(item.opts).filter(function (k) { return known.indexOf(k) < 0; })
        .map(function (k) { return { attr: k, def: '', desc: 'Set by the example.', type: /^[\[{]/.test(item.opts[k]) ? 'json' : 'text' }; });
      var det = h('details', { class: 'pg-sec', 'data-feat': item.name });
      if (!state.collapsed[item.name]) det.setAttribute('open', '');
      det.addEventListener('toggle', function () { state.collapsed[item.name] = !det.open; });
      det.appendChild(h('summary', { text: feat.title + ' options' }));
      var all = feat.options.concat(extras);
      if (!all.length) det.appendChild(h('p', { class: 'text-sm text-muted m-0 mt-2', text: 'No data-efx-* options.' }));
      all.forEach(function (o) { det.appendChild(optionField(item, feat, o)); });
      optsEl.appendChild(det);
    });
    paintErrors();
  }
  function paintErrors() {
    Array.prototype.forEach.call(optsEl.querySelectorAll('[data-err-for]'), function (el) {
      var msg = errorsByField[el.getAttribute('data-err-for')], ta = $(el.getAttribute('data-err-for'));
      el.textContent = msg ? 'Invalid JSON: ' + msg : '';
      el.style.color = msg ? 'var(--sh-danger,#dc2626)' : '';
      if (ta) { if (msg) ta.setAttribute('aria-invalid', 'true'); else ta.removeAttribute('aria-invalid'); }
    });
  }

  function setOpt(item, attr, v) {
    if (v === '' || v == null) delete item.opts[attr]; else item.opts[attr] = v;
    schedule();
  }

  /* ---------- preview ---------- */
  var timer = 0;
  function schedule() { clearTimeout(timer); timer = setTimeout(render, 250); }

  function render() {
    clearTimeout(timer);
    var out = build();
    paintErrors();
    $('pg-code-html').textContent = out.html;
    $('pg-code-head').textContent = headTags();
    var msgs = out.errors.concat(out.hints);
    statusEl.textContent = msgs.join(' ');
    statusEl.className = 'pg-status' + (out.errors.length ? ' err' : '');
    if (!out.errors.length && !out.hints.length) statusEl.textContent = '';
    try {
      if (window.Effix) Effix.destroy(stage);
      stage.innerHTML = out.html;
      if (window.Effix) Effix.init(stage);
    } catch (e) { /* a bad option must never break the page */ }
    syncChrome();
    try {
      history.replaceState(null, '', '#' + encodeState());
      $('pg-share').value = location.href;
    } catch (e) { $('pg-share').value = location.href.split('#')[0] + '#' + encodeState(); }
  }

  function syncChrome() {
    if (state.theme) stage.setAttribute('data-theme', state.theme); else stage.removeAttribute('data-theme');
    html.toggleAttribute('data-efx-reduce', state.reduce);
    $('pg-reduce').checked = state.reduce;
    $('pg-frame').style.inlineSize = state.width === 'full' ? '' : state.width + 'px';
    Array.prototype.forEach.call(document.querySelectorAll('[data-pg-theme]'), function (b) { b.setAttribute('aria-pressed', String(b.getAttribute('data-pg-theme') === state.theme)); });
    Array.prototype.forEach.call(document.querySelectorAll('[data-pg-width]'), function (b) { b.setAttribute('aria-pressed', String(b.getAttribute('data-pg-width') === state.width)); });
  }

  /* ---------- wiring ---------- */
  function selectionChanged() { syncList(); buildOptions(); render(); }

  listEl.addEventListener('change', function (e) {
    var t = e.target;
    if (t.matches('select[data-cls-for]')) {
      var it = selOf(t.getAttribute('data-cls-for'));
      if (it) { it.cls = t.value; render(); }
      return;
    }
    if (t.id === 'pg-chart-none') {
      state.sel = state.sel.filter(function (s) { return byName(s.name).kind !== 'chart'; });
      return selectionChanged();
    }
    if (t.name === 'pg-chart') { addFeature(t.value, null); return selectionChanged(); }
    if (t.name === 'pg-feat') {
      if (t.checked) addFeature(t.value, null); else removeFeature(t.value);
      selectionChanged();
    }
  });
  $('pg-search').addEventListener('input', filterList);
  $('pg-base').addEventListener('change', function () { state.base = this.value; render(); });
  $('pg-reduce').addEventListener('change', function () { state.reduce = this.checked; render(); });
  $('pg-replay').addEventListener('click', render);
  document.addEventListener('click', function (e) {
    var b = e.target.closest && e.target.closest('[data-pg-theme],[data-pg-width]');
    if (!b) return;
    if (b.hasAttribute('data-pg-theme')) { var v = b.getAttribute('data-pg-theme'); state.theme = state.theme === v ? '' : v; }
    else state.width = b.getAttribute('data-pg-width');
    render();
  });

  // page theme (same switch as the docs)
  var themeSel = $('page-theme'), saved = store.get('effix-page-theme');
  if (saved) html.setAttribute('data-theme', saved);
  if (themeSel) {
    themeSel.value = html.getAttribute('data-theme') || 'auto';
    themeSel.addEventListener('change', function () { html.setAttribute('data-theme', themeSel.value); store.set('effix-page-theme', themeSel.value); });
  }

  // boot
  var baseSel = $('pg-base');
  BASE_ORDER.forEach(function (k) { baseSel.appendChild(h('option', { value: k, text: BASES[k].label })); });
  buildList();
  if (!restoreState()) { addFeature('border', 'efx-border-spin'); }
  baseSel.value = state.base;
  syncList(); buildOptions(); filterList(); render();
})();
